export const TIME_SLOTS = (() => {
  const out: { value: string; label: string }[] = [];
  for (let m = 12 * 60; m <= 22 * 60; m += 30) {
    const h = Math.floor(m / 60);
    const mm = m % 60;
    const ap = h >= 12 ? "PM" : "AM";
    let h12 = h % 12;
    if (h12 === 0) h12 = 12;
    out.push({
      value: `${h < 10 ? "0" : ""}${h}:${mm === 0 ? "00" : mm}`,
      label: `${h12}:${mm === 0 ? "00" : mm} ${ap}`,
    });
  }
  return out;
})();
